def _generate_insights(data: Dict[str, Any]) -> List[str]:
    """Generate automated insights from analysis data."""
    insights = []

    for col in data["columns"]:
        stats = col["statistics"]
        name = col["name"]

        # High null rate
        if stats["count"]["null_pct"] > 30:
            insights.append(
                f"⚠️ Column `{name}` has a high null rate ({stats['count']['null_pct']}%). "
                f"Consider imputation or removal."
            )

        # Constant column
        if stats["unique"]["unique"] == 1 and stats["count"]["non_null"] > 1:
            insights.append(
                f"📌 Column `{name}` has only one unique value — it provides no information for analysis."
            )

        # High cardinality
        if stats["type"] == "categorical" and stats["unique"].get("unique", 0) > stats["count"]["non_null"] * 0.8:
            insights.append(
                f"🏷️ Column `{name}` has high cardinality ({stats['unique']['unique']} unique values). "
                f"Consider treating as an identifier rather than a categorical feature."
            )

        # Skewed distribution
        if stats["type"] == "numeric":
            skew = stats.get("skewness")
            if skew is not None:
                if abs(skew) > 2:
                    direction = "right" if skew > 0 else "left"
                    insights.append(
                        f"📈 Column `{name}` is heavily {direction}-skewed (skewness={skew}). "
                        f"Consider log transformation."
                    )
                elif abs(skew) > 1:
                    direction = "right" if skew > 0 else "left"
                    insights.append(
                        f"📊 Column `{name}` is moderately {direction}-skewed (skewness={skew})."
                    )

            # Outliers
            if "outliers" in col:
                out = col["outliers"]
                if out["count"] > 0:
                    insights.append(
                        f"🔍 Column `{name}` has {out['count']} outliers ({out['pct']}%) "
                        f"detected by IQR method."
                    )

    if not insights:
        insights.append("✅ Data quality looks good! No significant issues detected.")

    return insights


def save_report(content: str, file_path: str) -> None:
    """Save report content to file."""
    os.makedirs(os.path.dirname(file_path) if os.path.dirname(file_path) else ".", exist_ok=True)
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(content)
