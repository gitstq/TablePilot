def generate_analysis_data(table: DataTable, include_correlation: bool = False,
                           include_outliers: bool = False) -> Dict[str, Any]:
    """Generate comprehensive analysis data for report generation."""
    data = {
        "generated_at": datetime.now().isoformat(),
        "source": table.source,
        "shape": {"rows": table.num_rows, "columns": table.num_columns},
        "columns": [],
    }

    for col in table.columns:
        values = table.column(col)
        stats = descriptive_stats(values)
        col_data = {
            "name": col,
            "statistics": stats,
        }

        if include_outliers and stats["type"] == "numeric":
            col_data["outliers"] = detect_outliers_iqr(values)

        data["columns"].append(col_data)

    if include_correlation:
        data["correlation_matrix"] = correlation_matrix(table)

    return data


def to_markdown(data: Dict[str, Any], title: str = "Data Analysis Report") -> str:
    """Generate a Markdown format report."""
    lines = []

    lines.append(f"# 📊 {title}")
    lines.append("")
    lines.append(f"> Generated by **TablePilot** on {data['generated_at'][:10]}")
    lines.append(f"> Source: `{data['source']}`")
    lines.append(f"> Dataset: **{data['shape']['rows']}** rows × **{data['shape']['columns']}** columns")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Table of Contents
    lines.append("## 📑 Table of Contents")
    lines.append("")
    lines.append("- [📊 Dataset Overview](#-dataset-overview)")
    lines.append("- [📋 Column Analysis](#-column-analysis)")
    if "correlation_matrix" in data:
        lines.append("- [🔗 Correlation Matrix](#-correlation-matrix)")
    lines.append("- [💡 Insights](#-insights)")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Dataset Overview
    lines.append("## 📊 Dataset Overview")
    lines.append("")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| Rows | {data['shape']['rows']:,} |")
    lines.append(f"| Columns | {data['shape']['columns']} |")
    lines.append(f"| Memory (est.) | ~{data['shape']['rows'] * data['shape']['columns'] * 8 / 1024:.1f} KB |")
    lines.append(f"| Generated | {data['generated_at']} |")
    lines.append("")

    # Column Summary Table
    lines.append("### Column Summary")
    lines.append("")
    lines.append("| Column | Type | Non-Null | Null% | Unique |")
    lines.append("|--------|------|----------|-------|--------|")

    for col in data["columns"]:
        stats = col["statistics"]
        cnt = stats["count"]
        uniq = stats["unique"]
        lines.append(
            f"| `{col['name']}` | {stats['type']} | "
            f"{cnt['non_null']:,} | {cnt['null_pct']}% | {uniq['unique']} |"
        )
    lines.append("")

    # Column Analysis
    lines.append("## 📋 Column Analysis")
    lines.append("")

    for col in data["columns"]:
        stats = col["statistics"]
        lines.append(f"### `{col['name']}` ({stats['type']})")
        lines.append("")

        if stats["type"] == "numeric":
            s = stats
            lines.append("| Statistic | Value |")
            lines.append("|-----------|-------|")
            lines.append(f"| Count | {s['count']['non_null']:,} |")
            lines.append(f"| Mean | {s.get('mean', 'N/A')} |")
            lines.append(f"| Median | {s.get('median', 'N/A')} |")
            lines.append(f"| Std Dev | {s.get('std', 'N/A')} |")
            lines.append(f"| Min | {s.get('min', 'N/A')} |")
            lines.append(f"| Max | {s.get('max', 'N/A')} |")
            lines.append(f"| Range | {s.get('range', 'N/A')} |")
            lines.append(f"| Skewness | {s.get('skewness', 'N/A')} |")
            lines.append(f"| Kurtosis | {s.get('kurtosis', 'N/A')} |")
            lines.append(f"| CV | {s.get('cv', 'N/A')} |")
            lines.append("")

            if "percentiles" in s:
                p = s["percentiles"]
                lines.append("**Percentiles:**")
                lines.append("")
                lines.append("| P | Value |")
                lines.append("|---|-------|")
                for pk in ["p1", "p5", "p25", "p50", "p75", "p95", "p99"]:
                    if p.get(pk) is not None:
                        lines.append(f"| {pk.upper()} | {p[pk]} |")
                lines.append("")

            if "outliers" in col:
                out = col["outliers"]
                lines.append(f"**Outliers (IQR):** {out['count']} detected ({out['pct']}%)")
                if out["outliers"]:
                    sample = out["outliers"][:10]
                    lines.append(f"- Sample: {', '.join(str(v) for v in sample)}")
                lines.append("")
        else:
            # Categorical
            if "top_values" in stats:
                lines.append("**Top Values:**")
                lines.append("")
                lines.append("| Value | Count | Percentage |")
                lines.append("|-------|-------|------------|")
                for item in stats["top_values"][:10]:
                    lines.append(f"| `{item['value']}` | {item['count']:,} | {item['pct']}% |")
                lines.append("")

            lines.append(f"**Cardinality:** {stats.get('cardinality', 'N/A')}")
            lines.append("")

    # Correlation Matrix
    if "correlation_matrix" in data and data["correlation_matrix"]:
        lines.append("## 🔗 Correlation Matrix")
        lines.append("")
        corr = data["correlation_matrix"]
        cols = list(corr.keys())
        header = "| | " + " | ".join(f"`{c[:10]}`" for c in cols) + " |"
        sep = "|---|" + "|".join(["---:"] * len(cols)) + "|"
        lines.append(header)
        lines.append(sep)
        for row_name in cols:
            row = f"| `{row_name[:10]}` |"
            for col_name in cols:
                val = corr[row_name].get(col_name)
                if val is None:
                    row += " N/A |"
                else:
                    # Color code
                    if abs(val) >= 0.7:
                        row += f" **{val}** |"
                    elif abs(val) >= 0.4:
                        row += f" *{val}* |"
                    else:
                        row += f" {val} |"
            lines.append(row)
        lines.append("")

    # Insights
    lines.append("## 💡 Insights")
    lines.append("")

    insights = _generate_insights(data)
    for i, insight in enumerate(insights, 1):
        lines.append(f"{i}. {insight}")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("*Report generated by [TablePilot](https://github.com/gitstq/TablePilot) — Lightweight Tabular Data Intelligent Analysis Engine*")

    return "\n".join(lines)


